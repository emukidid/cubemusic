#!/usr/bin/env python3
"""Map the file extensions used in meta.c to the vgmstream meta parsers that
accept them (via their check_extensions() calls).

Usage: vgm_ext_map.py <vgmstream/src> <meta.c> [--emit <vgm_formats.txt>] [--missing <vgm_formats.txt>]
Prints, per init function, the meta.c extensions it claims and how many
meta.c entries that covers, plus the extensions nothing claims.

With --emit, writes a starting keep-list for the build (vgm_formats.txt):
every parser that claims a meta.c extension, plus every parser whose name
marks it as a GameCube/DSP format (some check their extension indirectly),
minus parsers for other platforms' codecs. Review the result by hand.
"""
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

src = Path(sys.argv[1])
meta_c = Path(sys.argv[2])

# extensions used by meta.c, with counts
ext_count = Counter()
for m in re.finditer(r'^\s*"[^"]*\.([A-Za-z0-9_]+)",', meta_c.read_text(errors="replace"), re.M):
    ext_count[m.group(1).lower()] += 1

# init functions in the master table, in order
table = re.findall(r'^\s+(init_vgmstream_\w+),', (src / "vgmstream_init.c").read_text(), re.M)

# for every function body in meta/*.c, collect check_extensions strings. A
# parser often checks the extension in a helper in the same file (adx.c:
# init_vgmstream_adx -> init_vgmstream_adx_subkey), so calls to functions
# defined in the same file are followed too.
func_re = re.compile(r'^[A-Za-z_][\w \t\*]*?\b(\w+)\s*\([^;{]*\)\s*\{', re.M)
ext_re = re.compile(r'check_extensions\s*\(\s*\w+\s*,\s*"([^"]*)"')
func_exts = defaultdict(set)
for f in sorted((src / "meta").glob("*.c")):
    text = f.read_text(errors="replace")
    starts = [(m.start(), m.group(1)) for m in func_re.finditer(text)]
    bodies, own = {}, defaultdict(set)
    for i, (pos, name) in enumerate(starts):
        end = starts[i + 1][0] if i + 1 < len(starts) else len(text)
        bodies[name] = text[pos:end]
        for em in ext_re.finditer(text, pos, end):
            for e in em.group(1).split(","):
                own[name].add(e.strip().lower())
    for name in bodies:
        seen, todo = {name}, [name]
        while todo:
            fn = todo.pop()
            func_exts[name] |= own[fn]
            for other in bodies:
                if other not in seen and re.search(r'\b' + re.escape(other) + r'\b', bodies[fn]):
                    seen.add(other)
                    todo.append(other)

claimed = set()
for fn in table:
    hits = sorted(e for e in func_exts.get(fn, ()) if e in ext_count)
    if hits:
        claimed.update(hits)
        print(f"{fn:45s} {sum(ext_count[e] for e in hits):6d}  {','.join(hits)}")

print("\n# extensions with no claiming parser in the init table:")
for e, c in ext_count.most_common():
    if e not in claimed:
        print(f"  {e:12s} {c}")

if "--missing" in sys.argv:
    have = Path(sys.argv[sys.argv.index("--missing") + 1]).read_text().split()
    have = {"init_vgmstream_" + h for h in have if not h.startswith("#")}
    print("\n# parsers claiming meta.c extensions that the build leaves out:")
    for fn in table:
        hits = sorted(e for e in func_exts.get(fn, ()) if e in ext_count)
        if hits and fn not in have:
            print(f"  {fn[len('init_vgmstream_'):]:40s} {sum(ext_count[e] for e in hits):6d}  {','.join(hits)}")

if "--emit" in sys.argv:
    out = Path(sys.argv[sys.argv.index("--emit") + 1])
    gc_name = re.compile(r'ngc|dsp|_gc|gcub|gca|idsp|halpst|thp|dtk|afc|_ast|rs03|cstr|jaudio|txtp|txth|genh')
    other_platform = re.compile(r'xbox|xma|psf_|ffmpeg|_ps2|ps_headerless|_x360|_3ds|_wiiu|_switch|nus3')
    keep = []
    for fn in table:
        claims = any(e in ext_count for e in func_exts.get(fn, ()))
        if (claims or gc_name.search(fn)) and not other_platform.search(fn) and fn not in keep:
            keep.append(fn)
    with out.open("w", newline="\n") as f:
        f.write("# vgmstream parsers built into cubemusic, one per line (init_vgmstream_ prefix\n"
                "# dropped). Order doesn't matter: the build keeps upstream's table order.\n"
                "# Generated by tools/vgm_ext_map.py from meta.c, then edited by hand.\n")
        for fn in keep:
            f.write(fn[len("init_vgmstream_"):] + "\n")
    print(f"\nwrote {len(keep)} of {len(table)} parsers to {out}")
