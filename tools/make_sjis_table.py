"""Writes source/sjis_table.c: Shift-JIS (cp932) two-byte codes to Unicode.

Lead bytes 0x81-0x9F and 0xE0-0xFC, trail bytes 0x40-0xFC; 0 = not a
character. Run from the project folder: python tools/make_sjis_table.py
"""
import os

LEADS = list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD))
TRAIL0, TRAILS = 0x40, 0xFD - 0x40

vals = []
for lead in LEADS:
    for trail in range(TRAIL0, TRAIL0 + TRAILS):
        try:
            ch = bytes((lead, trail)).decode("cp932")
            cp = ord(ch) if len(ch) == 1 and ord(ch) < 0x10000 else 0
        except UnicodeDecodeError:
            cp = 0
        vals.append(cp)

out = os.path.join(os.path.dirname(__file__), "..", "source", "sjis_table.c")
with open(out, "w", newline="\n") as f:
    f.write("/* sjis_table.c -- generated by tools/make_sjis_table.py, do not edit */\n")
    f.write("#include <stdint.h>\n\n")
    f.write("const uint16_t sjis_table[%d] = {\n" % len(vals))
    for i in range(0, len(vals), 12):
        f.write("\t" + ", ".join("0x%04X" % v for v in vals[i:i + 12]) + ",\n")
    f.write("};\n")
print(len(vals), "entries,", sum(1 for v in vals if v), "characters")
